// Command sync-indexes copies WeKan's database indexes into
// web/wekan_indexes.go: every ensureIndex(Collection, {keys}, {options}) call
// of WeKan's server code, with the collection's name, its keys in order and
// its sparse, unique and expireAfterSeconds options. Weddy creates them at
// startup, so a database Weddy alone runs - no WeKan has ever started on it -
// has the indexes WeKan's queries, and Weddy's same queries, rely on (#6892).
//
//	go run ./cmd/sync-indexes /path/to/wekan
//
// WeKan's ensureIndex calls stay the one place an index is chosen; this
// copies, it never edits. A call whose collection is not a variable bound to
// new Mongo.Collection('name'), or whose keys are not a literal, is skipped.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	collRe  = regexp.MustCompile(`(?:const|let|var)\s+(\w+)\s*=\s*new Mongo\.Collection\(\s*['"]([^'"]+)['"]`)
	indexRe = regexp.MustCompile(`ensureIndex\(\s*(\w+)\s*,\s*(\{[^{}]*\})\s*(?:,\s*(\{[^{}]*\}))?\s*\)`)
	usersRe = regexp.MustCompile(`(?:const|let|var)\s+(\w+)\s*=\s*Meteor\.users\b`)
	pairRe  = regexp.MustCompile(`(?:'([^']+)'|"([^"]+)"|([A-Za-z_$][\w$]*))\s*:\s*([^,}]+)`)
)

type index struct {
	coll    string
	keys    [][2]string
	options []string
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run ./cmd/sync-indexes /path/to/wekan")
		os.Exit(2)
	}
	root := os.Args[1]
	var files []string
	for _, dir := range []string{"models", "server", "packages"} {
		_ = filepath.WalkDir(filepath.Join(root, dir), func(p string, d os.DirEntry, err error) error {
			if err != nil {
				return nil
			}
			if d.IsDir() && (d.Name() == "node_modules" || d.Name() == "tests" || d.Name() == ".npm") {
				return filepath.SkipDir
			}
			if !d.IsDir() && strings.HasSuffix(p, ".js") {
				files = append(files, p)
			}
			return nil
		})
	}
	sort.Strings(files)
	names := map[string]string{}
	sources := map[string]string{}
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			continue
		}
		sources[f] = string(raw)
		// Meteor's own accounts collection is named 'users'.
		for _, m := range usersRe.FindAllStringSubmatch(string(raw), -1) {
			if _, seen := names[m[1]]; !seen {
				names[m[1]] = "users"
			}
		}
		for _, m := range collRe.FindAllStringSubmatch(string(raw), -1) {
			if _, seen := names[m[1]]; !seen {
				names[m[1]] = m[2]
			}
		}
	}
	seen := map[string]bool{}
	var out []index
	skipped := 0
	for _, f := range files {
		for _, m := range indexRe.FindAllStringSubmatch(sources[f], -1) {
			coll, ok := names[m[1]]
			if !ok {
				skipped++
				continue
			}
			ix := index{coll: coll}
			good := true
			for _, p := range pairRe.FindAllStringSubmatch(m[2], -1) {
				key := p[1] + p[2] + p[3]
				val := strings.TrimSpace(p[4])
				if val != "1" && val != "-1" {
					good = false
					break
				}
				ix.keys = append(ix.keys, [2]string{key, val})
			}
			if !good || len(ix.keys) == 0 {
				skipped++
				continue
			}
			for _, p := range pairRe.FindAllStringSubmatch(m[3], -1) {
				key, val := p[1]+p[2]+p[3], strings.TrimSpace(p[4])
				switch key {
				case "sparse", "unique":
					if val == "true" {
						ix.options = append(ix.options, "Set"+strings.ToUpper(key[:1])+key[1:]+"(true)")
					}
				case "expireAfterSeconds":
					if n, ok := evalProduct(val); ok {
						ix.options = append(ix.options, "SetExpireAfterSeconds("+strconv.Itoa(n)+")")
					}
				}
			}
			id := fmt.Sprint(ix.coll, ix.keys, ix.options)
			if !seen[id] {
				seen[id] = true
				out = append(out, ix)
			}
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].coll < out[j].coll })
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/sync-indexes from WeKan's ensureIndex calls; DO NOT EDIT.\n\npackage web\n\n")
	b.WriteString("import (\n\t\"go.mongodb.org/mongo-driver/v2/bson\"\n\t\"go.mongodb.org/mongo-driver/v2/mongo/options\"\n)\n\n")
	b.WriteString("// wekanIndexes are WeKan's indexes, created at startup (wekan_indexes_ensure.go).\nvar wekanIndexes = []wekanIndex{\n")
	for _, ix := range out {
		var keys []string
		for _, k := range ix.keys {
			keys = append(keys, fmt.Sprintf("{Key: %q, Value: %s}", k[0], k[1]))
		}
		opts := "nil"
		if len(ix.options) > 0 {
			opts = "options.Index()." + strings.Join(ix.options, ".")
		}
		fmt.Fprintf(&b, "\t{%q, bson.D{%s}, %s},\n", ix.coll, strings.Join(keys, ", "), opts)
	}
	b.WriteString("}\n")
	dst := filepath.Join("web", "wekan_indexes.go")
	if err := os.WriteFile(dst, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("%d indexes of %d collections; %d calls skipped\n", len(out), countColls(out), skipped)
}

// evalProduct reads an integer or a product of integers (30 * 24 * 60 * 60).
func evalProduct(s string) (int, bool) {
	n := 1
	for _, f := range strings.Split(s, "*") {
		v, err := strconv.Atoi(strings.TrimSpace(f))
		if err != nil {
			return 0, false
		}
		n *= v
	}
	return n, true
}

func countColls(ix []index) int {
	set := map[string]bool{}
	for _, i := range ix {
		set[i.coll] = true
	}
	return len(set)
}
